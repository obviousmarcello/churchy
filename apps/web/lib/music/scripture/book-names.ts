const NAMES = {
  hu: new Map(HUNGARIAN_NAMES.map((name, index) => [BOOK_IDS[index], name])),
  en: new Map(ENGLISH_NAMES.map((name, index) => [BOOK_IDS[index], name])),
};

/** The full name of a book in the language of the app, e.g. "János" or "John". English for the other languages. */
export function bookName(id: string, locale: string): string {
  return (locale === "hu" ? NAMES.hu : NAMES.en).get(id) ?? id;
}

/** The number of books with names: the tests check that it is the number of `BOOKS`. */
export const BOOK_NAME_COUNTS = { hu: HUNGARIAN_NAMES.length, en: ENGLISH_NAMES.length };
