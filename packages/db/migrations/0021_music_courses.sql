      when f.in_draft then
        jsonb_set(
          c.draft,
          '{areaIds}',
          coalesce(
            (
              select jsonb_agg(e.value)
              from jsonb_array_elements(c.draft -> 'areaIds') as e (value)
              where e.value <> to_jsonb(old.id)
            ),
            '[]'::jsonb
          )
        )
      else c.draft
    end,
    revision = c.revision + 1
  from (
    select
      c2.id,
      coalesce(c2.draft -> 'areaIds' ? old.id::text, false) as in_draft,
      exists (
        select 1 from public.course_areas ca where ca.course_id = c2.id and ca.area_id = old.id
      ) as in_published,
      exists (
        select 1
        from public.course_areas ca
        join public.service_areas a on a.id = ca.area_id
        where ca.course_id = c2.id and ca.area_id <> old.id
      ) as has_other_area
    from public.courses c2
  ) f
  where f.id = c.id
    and (f.in_draft or f.in_published);
  return old;
end;
