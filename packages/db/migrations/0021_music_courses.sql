language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_course public.courses%rowtype := public.lock_course(p_id, p_revision);
  v_doc jsonb;
begin
  if v_course.id is null then
    return null;
  end if;
  v_doc := public.course_document_with_area_order(p_doc);
  perform public.check_course_lessons(p_id, v_doc);
  perform public.check_course_image(p_id, v_doc);
  if jsonb_array_length(v_doc -> 'lessons') = 0 then
    raise exception 'a published course needs a lesson' using errcode = 'P0001', hint = 'no_lessons';
  end if;

  update public.courses
  set
    title = v_doc ->> 'title',
    language = v_doc ->> 'language',
    description = v_doc ->> 'description',
    icon = v_doc ->> 'icon',
    image_path = v_doc ->> 'imagePath',
    is_published = true,
    published_at = now(),
    draft = null,
    areas_lost = false,
    revision = revision + 1
  where id = p_id
  returning revision into v_course.revision;

  delete from public.course_areas where course_id = p_id;
  insert into public.course_areas (course_id, area_id)
  select p_id, area_id::uuid
  from jsonb_array_elements_text(v_doc -> 'areaIds') as area_id;

  update public.course_lessons
  set removed_at = now()
  where course_id = p_id
    and removed_at is null
    and id not in (select (e.value ->> 'id')::uuid from jsonb_array_elements(v_doc -> 'lessons') as e (value));

  insert into public.course_lessons (id, course_id, position, title, video_url, body, links)
  select
    (e.value ->> 'id')::uuid,
    p_id,
    (e.ordinality - 1)::integer,
    e.value ->> 'title',
    e.value ->> 'videoUrl',
    e.value -> 'body',
    e.value -> 'links'
  from jsonb_array_elements(v_doc -> 'lessons') with ordinality as e (value, ordinality)
  on conflict (id) do update
  set
    position = excluded.position,
    title = excluded.title,
    video_url = excluded.video_url,
    body = excluded.body,
    links = excluded.links
  where public.course_lessons.course_id = excluded.course_id;

  return v_course.revision;
end;
$$;
