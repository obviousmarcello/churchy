create or replace function public.restore_course_lesson(p_course_id uuid, p_lesson_id uuid, p_revision integer)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_course public.courses%rowtype := public.lock_course(p_course_id, p_revision);
  v_lesson public.course_lessons%rowtype;
  v_restored jsonb;
  v_draft jsonb;
begin
  if v_course.id is null then
    return null;
  end if;

  select * into v_lesson
  from public.course_lessons
  where id = p_lesson_id and course_id = p_course_id and removed_at is not null;
  if not found then
    return null;
  end if;

  -- Before the restore, so the published course is without the lesson.
  v_draft := coalesce(v_course.draft, public.course_document(p_course_id));
  if jsonb_array_length(v_draft -> 'lessons') >= 100
    or (
      v_lesson.is_published
      and (select count(*) from public.course_lessons where course_id = p_course_id and removed_at is null) >= 100
    )
  then
    raise exception 'a course has at most 100 lessons' using errcode = 'P0001', hint = 'too_many_lessons';
  end if;
  v_restored := coalesce(v_lesson.draft, public.course_lesson_document(v_lesson));

  if v_lesson.is_published then
    update public.course_lessons
    set
      removed_at = null,
      draft = null,
      position = coalesce(
        (select max(position) + 1 from public.course_lessons where course_id = p_course_id and removed_at is null),
        0
      )
    where id = p_lesson_id;
  else
    delete from public.course_lessons where id = p_lesson_id;
  end if;

  v_draft := jsonb_set(v_draft, '{lessons}', (v_draft -> 'lessons') || jsonb_build_array(v_restored));
  if v_course.published_at is not null and v_draft = public.course_document(p_course_id) then
    v_draft := null;
  end if;

  update public.courses set draft = v_draft, revision = revision + 1 where id = p_course_id
  returning revision into v_course.revision;

  return jsonb_build_object('revision', v_course.revision, 'lesson', v_restored);
end;
$$;
