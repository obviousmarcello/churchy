-- Deletes the courses and lessons removed more than 90 days ago (keep in sync with `REMOVED_KEEP_DAYS`).
create or replace function public.purge_removed_courses()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_courses integer;
  v_lessons integer;
begin
  delete from public.courses where removed_at <= now() - interval '90 days';
  get diagnostics v_courses = row_count;
  delete from public.course_lessons where removed_at <= now() - interval '90 days';
  get diagnostics v_lessons = row_count;
  return v_courses + v_lessons;
end;
$$;
