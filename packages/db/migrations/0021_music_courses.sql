returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  -- Changes of the order wait for each other here.
  perform pg_advisory_xact_lock(hashtext('public.courses'));

  if cardinality(p_ids) is distinct from (select count(*) from public.courses where removed_at is null)
    or cardinality(p_ids) <> (select count(distinct o.course_id) from unnest(p_ids) as o (course_id))
    or exists (
      select 1 from unnest(p_ids) as o (course_id)
      where not exists (select 1 from public.courses c where c.id = o.course_id and c.removed_at is null)
    )
  then
    return false;
  end if;

  update public.courses c
  set position = o.ordinality
  from unnest(p_ids) with ordinality as o (id, ordinality)
  where c.id = o.id and c.position is distinct from o.ordinality;
  return true;
end;
