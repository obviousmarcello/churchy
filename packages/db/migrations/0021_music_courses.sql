create or replace function public.remove_course_lesson(p_course_id uuid, p_lesson_id uuid, p_revision integer)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_course public.courses%rowtype := public.lock_course(p_course_id, p_revision);
  v_lesson public.course_lessons%rowtype;
  v_draft_lesson jsonb;
  v_draft jsonb;
  v_unpublished boolean := false;
begin
  if v_course.id is null then
    return null;
  end if;

  select e.value into v_draft_lesson
  from jsonb_array_elements(v_course.draft -> 'lessons') as e (value)
  where e.value ->> 'id' = p_lesson_id::text;

  select * into v_lesson
  from public.course_lessons
  where id = p_lesson_id and course_id = p_course_id and removed_at is null;

  if v_lesson.id is not null then
    update public.course_lessons
    set
      removed_at = now(),
      draft = case when v_draft_lesson = public.course_lesson_document(v_lesson) then null else v_draft_lesson end
    where id = p_lesson_id;
  elsif v_draft_lesson is not null then
    insert into public.course_lessons (id, course_id, position, title, video_url, body, links, is_published, removed_at)
    values (
      p_lesson_id,
      p_course_id,
      0,
      v_draft_lesson ->> 'title',
      v_draft_lesson ->> 'videoUrl',
      v_draft_lesson -> 'body',
      v_draft_lesson -> 'links',
      false,
      now()
    );
  else
    return null;
  end if;

  v_draft := v_course.draft;
  if v_draft is not null then
    v_draft := jsonb_set(
      v_draft,
      '{lessons}',
      coalesce(
        (
          select jsonb_agg(e.value order by e.ordinality)
          from jsonb_array_elements(v_draft -> 'lessons') with ordinality as e (value, ordinality)
          where e.value ->> 'id' <> p_lesson_id::text
        ),
        '[]'::jsonb
      )
    );
    if v_course.published_at is not null and v_draft = public.course_document(p_course_id) then
      v_draft := null;
    end if;
  end if;

  if v_course.is_published
    and not exists (select 1 from public.course_lessons where course_id = p_course_id and removed_at is null)
  then
    v_unpublished := true;
  end if;

  update public.courses
  set
    draft = v_draft,
    is_published = is_published and not v_unpublished,
    revision = revision + 1
  where id = p_course_id
  returning revision into v_course.revision;

  return jsonb_build_object('revision', v_course.revision, 'unpublished', v_unpublished);
end;
$$;
