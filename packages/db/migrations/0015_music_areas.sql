create or replace function public.set_service_area_order(p_parent_id uuid, p_ids uuid[])
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  perform pg_advisory_xact_lock(hashtext('public.service_areas'));

  if cardinality(p_ids) is distinct from (
      select count(*) from public.service_areas where parent_id is not distinct from p_parent_id
    )
    or cardinality(p_ids) <> (select count(distinct o.area_id) from unnest(p_ids) as o (area_id))
    or exists (
      select 1 from unnest(p_ids) as o (area_id)
      where not exists (
        select 1 from public.service_areas a where a.id = o.area_id and a.parent_id is not distinct from p_parent_id
      )
    )
  then
    return false;
  end if;

  -- The smallest positions of the siblings, in the new order: the other groups keep theirs.
  update public.service_areas a
  set position = s.position
  from (
    select o.id, p.position
    from unnest(p_ids) with ordinality as o (id, ordinality)
    join (
      select position, row_number() over (order by position) as ordinality
      from public.service_areas
      where parent_id is not distinct from p_parent_id
    ) as p on p.ordinality = o.ordinality
  ) as s
  where a.id = s.id and a.position is distinct from s.position;

  return true;
end;
$$;
