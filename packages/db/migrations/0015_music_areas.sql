set search_path = ''
as $$
declare
  v_ids uuid[] := array(select distinct unnest(p_area_ids));
begin
  if p_user_id is null or p_area_ids is null or array_position(p_area_ids, null) is not null then
    raise exception 'the user and the groups are required' using errcode = '22023';
