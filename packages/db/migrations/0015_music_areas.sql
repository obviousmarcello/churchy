create or replace function public.place_service_area(
  p_id uuid,
  p_parent_id uuid,
  p_ids uuid[],
  p_grant_roles boolean default false,
  p_actor_id uuid default null
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_parent_id uuid;
  v_has_members boolean;
begin
  perform pg_advisory_xact_lock(hashtext('public.service_areas'));

  select parent_id into v_parent_id from public.service_areas where id = p_id;
  if not found then
    return false;
  end if;

  -- The groups there after the move: the current ones, without and with this group.
  if p_id <> all (p_ids)
    or cardinality(p_ids) <> (select count(distinct o.area_id) from unnest(p_ids) as o (area_id))
    or cardinality(p_ids) <> 1 + (
      select count(*) from public.service_areas
      where parent_id is not distinct from p_parent_id and id <> p_id
    )
    or exists (
      select 1 from unnest(p_ids) as o (area_id)
      where o.area_id <> p_id
        and not exists (
          select 1 from public.service_areas a where a.id = o.area_id and a.parent_id is not distinct from p_parent_id
        )
    )
  then
    return false;
  end if;

  if v_parent_id is distinct from p_parent_id then
    v_has_members := exists (
      select 1
      from public.service_area_paths d
      join public.service_area_members m on m.area_id = d.descendant_id
      where d.ancestor_id = p_id
    );

    -- A role from the new place that the group does not have yet.
    if not p_grant_roles
      and v_has_members
      and exists (
        select g.role
        from public.service_area_paths p
        join public.service_area_roles g on g.area_id = p.ancestor_id
        where p.descendant_id = p_parent_id
        except
        select g.role
        from public.service_area_paths p
        join public.service_area_roles g on g.area_id = p.ancestor_id
        where p.descendant_id = p_id
      )
    then
      raise exception 'only a superadmin moves members under a group with roles' using errcode = 'P0001', hint = 'group_roles';
    end if;

    -- A role from the old place that the new place and the group itself do not give.
    if not p_grant_roles
      and v_has_members
      and not public.leads_service_area(p_id, p_actor_id)
      and exists (
        select g.role
        from public.service_area_paths p
        join public.service_area_roles g on g.area_id = p.ancestor_id
        where p.descendant_id = v_parent_id
        except
        select g.role
        from public.service_area_paths p
        join public.service_area_roles g on g.area_id = p.ancestor_id
        where p.descendant_id = p_parent_id
        except
        select g.role from public.service_area_roles g where g.area_id = p_id
      )
    then
      raise exception 'only a superadmin or a leader moves members away from a role'
        using errcode = 'P0001', hint = 'group_roles_remove';
    end if;

    perform public.move_service_area(p_id, p_parent_id);
  end if;

  -- The check above holds under the lock, so the order is always possible.
  if not public.set_service_area_order(p_parent_id, p_ids) then
    raise exception 'the groups changed during the move' using errcode = 'P0001', hint = 'group_order';
  end if;
  return true;
end;
$$;
