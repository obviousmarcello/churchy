create or replace function public.set_service_area_members(
  p_area_id uuid,
  p_members jsonb,
  p_grant_roles boolean default false,
  p_actor_id uuid default null
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_is_root boolean;
  v_leaders_change boolean;
begin
  if jsonb_typeof(p_members) is distinct from 'array' then
    raise exception 'members must be an array' using errcode = '22023';
  end if;
  if jsonb_array_length(p_members) > 500 then
    raise exception 'too many members' using errcode = '22023';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_members) as e (value)
    where jsonb_typeof(e.value -> 'user_id') is distinct from 'string'
      or jsonb_typeof(e.value -> 'is_leader') is distinct from 'boolean'
  ) then
    raise exception 'each member needs user_id and is_leader' using errcode = '22023';
  end if;

  -- The same lock as the changes of the tree and of the roles: a move of a
  -- group and a new role wait for this change, and the other way round.
  perform pg_advisory_xact_lock(hashtext('public.service_areas'));

  select is_root into v_is_root from public.service_areas where id = p_area_id for no key update;
  if not found then
    return false;
  end if;

  if not p_grant_roles then
    if public.service_area_gives_roles(p_area_id)
      and exists (
        select 1
        from jsonb_array_elements(p_members) as e (value)
        where not exists (
          select 1 from public.service_area_members m
          where m.area_id = p_area_id and m.user_id = (e.value ->> 'user_id')::uuid
        )
      )
    then
      raise exception 'only a superadmin adds members to a group with roles' using errcode = 'P0001', hint = 'group_roles';
    end if;

    v_leaders_change := exists (
      (
        select m.user_id from public.service_area_members m where m.area_id = p_area_id and m.is_leader
        except
        select (e.value ->> 'user_id')::uuid
        from jsonb_array_elements(p_members) as e (value)
        group by (e.value ->> 'user_id')::uuid
        having bool_or((e.value ->> 'is_leader')::boolean)
      )
      union all
      (
        select (e.value ->> 'user_id')::uuid
        from jsonb_array_elements(p_members) as e (value)
        group by (e.value ->> 'user_id')::uuid
        having bool_or((e.value ->> 'is_leader')::boolean)
        except
        select m.user_id from public.service_area_members m where m.area_id = p_area_id and m.is_leader
      )
    );

    if v_is_root and v_leaders_change then
      raise exception 'only a superadmin changes the leaders of the root group' using errcode = 'P0001', hint = 'root_leaders';
    end if;

    if public.service_area_gives_roles(p_area_id)
      and not public.leads_service_area(p_area_id, p_actor_id)
      and (
        v_leaders_change
        or exists (
          select 1 from public.service_area_members m
          where m.area_id = p_area_id
            and not exists (
              select 1 from jsonb_array_elements(p_members) as e (value) where (e.value ->> 'user_id')::uuid = m.user_id
            )
        )
      )
    then
      raise exception 'only a superadmin or a leader removes members from a group with roles'
        using errcode = 'P0001', hint = 'group_roles_remove';
    end if;
  end if;

  delete from public.service_area_members m
  where m.area_id = p_area_id
    and not exists (
      select 1 from jsonb_array_elements(p_members) as e (value) where (e.value ->> 'user_id')::uuid = m.user_id
    );

  insert into public.service_area_members (area_id, user_id, is_leader)
  select p_area_id, (e.value ->> 'user_id')::uuid, bool_or((e.value ->> 'is_leader')::boolean)
  from jsonb_array_elements(p_members) as e (value)
  group by (e.value ->> 'user_id')::uuid
  on conflict (tenant_id, area_id, user_id) do update
  set is_leader = excluded.is_leader
  where public.service_area_members.is_leader is distinct from excluded.is_leader;

  return true;
end;
$$;
