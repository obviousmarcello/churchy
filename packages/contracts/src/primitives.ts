import { z } from "zod";

/**
 * Shared primitive schemas. Conventions (fixed by the lead for all packages):
 * - civil dates are ISO `YYYY-MM-DD` strings, times are `HH:mm`, instants are ISO-8601 with offset;
 * - all local-time logic is Europe/Budapest; ISO weekday 1 = Monday … 7 = Sunday;
 * - ids are opaque strings; fields are camelCase (snake_case mapping is the DB adapter's job).
 */

/** Opaque entity id (uuid in the DB adapter, readable ids in the mock). */
export const IdSchema = z.string().min(1).max(100);
export type Id = z.infer<typeof IdSchema>;

/** Civil date `YYYY-MM-DD` (calendar-valid, incl. leap years). */
export const IsoDateSchema = z.iso.date();
export type IsoDate = z.infer<typeof IsoDateSchema>;

/** Local wall-clock time `HH:mm` (24 h), interpreted in Europe/Budapest. */
export const IsoTimeSchema = z
  .string()
  .regex(/^([01]\d|2[0-3]):[0-5]\d$/, { message: "Expected HH:mm" });
export type IsoTime = z.infer<typeof IsoTimeSchema>;

/** Instant: ISO-8601 date-time with `Z` or a numeric offset, e.g. `2026-11-15T10:00:00+01:00`. */
export const IsoDateTimeSchema = z.iso.datetime({ offset: true });
export type IsoDateTime = z.infer<typeof IsoDateTimeSchema>;

/** ISO weekday: 1 = Monday … 7 = Sunday. */
export const IsoWeekdaySchema = z.number().int().min(1).max(7);
export type IsoWeekday = 1 | 2 | 3 | 4 | 5 | 6 | 7;

/** URL segment without diacritics (generated by `packages/hu`). */
export const SlugSchema = z
  .string()
  .max(120)
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, { message: "Expected a lowercase slug" });

export const EmailSchema = z.email();

/** Phone number as entered/normalized (`+36 30 123 4567`); formatting lives in `packages/hu`. */
export const PhoneSchema = z
  .string()
  .regex(/^\+?[0-9][0-9 ()/-]{5,19}$/, { message: "Expected a phone number" });

export const HexColorSchema = z
  .string()
  .regex(/^#[0-9a-fA-F]{6}$/, { message: "Expected #rrggbb" });

/** Non-empty, trimmed single-line text. */
export const TextSchema = z.string().trim().min(1).max(500);

/** Hungarian address, rendered as `1011 Budapest, Fő utca 1.` by `packages/hu`. */
export const AddressSchema = z.object({
  postalCode: z.string().regex(/^\d{4}$/, { message: "Expected a 4-digit postal code" }),
  city: TextSchema,
  /** Street, house number and anything else on the first line, e.g. `Fő utca 1.` */
  line1: TextSchema,
  line2: z.string().max(200).nullable().default(null),
});
export type Address = z.infer<typeof AddressSchema>;

export const GeoPointSchema = z.object({
  lat: z.number().min(-90).max(90),
  lng: z.number().min(-180).max(180),
});
export type GeoPoint = z.infer<typeof GeoPointSchema>;

/**
 * Rich text stored as ProseMirror/Tiptap JSON (never HTML). The node tree is validated
 * structurally here; the allow-list renderer decides what is rendered.
 */
export const RichTextNodeSchema = z.looseObject({ type: z.string().min(1) });
export const RichTextSchema = z.object({
  type: z.literal("doc"),
  content: z.array(RichTextNodeSchema).default([]),
});
export type RichText = z.infer<typeof RichTextSchema>;

/** Musical key in English letter notation (`G`, `F#m`, `Bb`); H/B naming is display-only (L-11). */
export const MusicalKeySchema = z
  .string()
  .regex(/^[A-G](#|b)?m?$/, { message: "Expected a key such as G, F#m or Bb" });

/** Weekly opening / office hours with date-range exceptions (FR-008). */
export const WeeklyHoursSchema = z.array(
  z.object({ weekday: IsoWeekdaySchema, from: IsoTimeSchema, to: IsoTimeSchema }),
);
export type WeeklyHours = z.infer<typeof WeeklyHoursSchema>;

export const OpeningHoursSchema = z.object({
  weekly: WeeklyHoursSchema.default([]),
  exceptions: z
    .array(
      z.object({
        from: IsoDateSchema,
        to: IsoDateSchema,
        closed: z.boolean(),
        hours: WeeklyHoursSchema.optional(),
        note: z.string().max(300).nullable().default(null),
      }),
    )
    .default([]),
});
export type OpeningHours = z.infer<typeof OpeningHoursSchema>;

/** Created/updated timestamps carried by most entities (set by the adapter). */
export const TimestampsShape = {
  createdAt: IsoDateTimeSchema,
  updatedAt: IsoDateTimeSchema,
};

/** ISO weekday (1–7) of a civil date, independent of the process time zone. */
export function isoWeekdayOf(date: IsoDate): IsoWeekday {
  const day = new Date(`${date}T12:00:00Z`).getUTCDay();
  return (day === 0 ? 7 : day) as IsoWeekday;
}
