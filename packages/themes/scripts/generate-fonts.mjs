// Regenerates src/css/fonts.css: self-hosted @fontsource faces (latin + latin-ext only, woff2,
// font-display: swap) plus size-adjusted local fallback faces, so the swap does not shift layout.
// Run: node scripts/generate-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";

/** Fallback metrics measured against Arial / Times New Roman (Liberation) with fontkit. */
const FAMILIES = [
  {
    name: "Cormorant Garamond",
    pkg: "cormorant-garamond",
    weights: [500, 600, 700],
    serif: true,
    adjust: [97.46, 94.81, 29.45],
  },
  {
    name: "Source Sans 3",
    pkg: "source-sans-3",
    weights: [400, 600, 700],
    adjust: [93.78, 109.19, 42.65],
  },
  { name: "Inter", pkg: "inter", weights: [400, 600, 700], adjust: [106.92, 90.6, 22.56] },
  { name: "Nunito", pkg: "nunito", weights: [700, 800], adjust: [104.47, 96.78, 33.79] },
  {
    name: "Nunito Sans",
    pkg: "nunito-sans",
    weights: [400, 600, 700],
    adjust: [100.29, 100.81, 35.2],
  },
];

let out = `/*
 * Self-hosted fonts via @fontsource, latin + latin-ext subsets only (ő/ű live in latin-ext), woff2
 * only, font-display: swap. Each family also has a "<name> Fallback" face: a local system font
 * scaled to the web font's metrics (size-adjust + ascent/descent overrides), so the swap from
 * fallback to web font does not move the layout (CLS). The font stacks in registry.ts list the
 * fallback face before the generic fallbacks.
 * Generated by scripts/generate-fonts.mjs: do not edit by hand.
 */
`;
for (const f of FAMILIES) {
  const [size, asc, desc] = f.adjust;
  const local = f.serif
    ? 'local("Times New Roman"), local("Liberation Serif"), local("Times")'
    : 'local("Arial"), local("Liberation Sans"), local("Helvetica")';
  out += `\n@font-face {\n  font-family: "${f.name} Fallback";\n  src: ${local};\n  size-adjust: ${size}%;\n  ascent-override: ${asc}%;\n  descent-override: ${desc}%;\n  line-gap-override: 0%;\n}\n`;
  for (const w of f.weights) {
    const css = readFileSync(
      new URL(`../node_modules/@fontsource/${f.pkg}/${w}.css`, import.meta.url),
      "utf8",
    );
    for (const subset of ["latin-ext", "latin"]) {
      const m = css.match(
        new RegExp(`/\\* ${f.pkg}-${subset}-${w}-normal \\*/[\\s\\S]*?unicode-range:\\s*([^;]+);`),
      );
      if (!m) throw new Error(`${f.pkg} ${subset} ${w}`);
      const range = m[1]
        .split(",")
        .map((s) => s.trim())
        .join(", ");
      out += `\n@font-face {\n  font-family: "${f.name}";\n  font-style: normal;\n  font-weight: ${w};\n  font-display: swap;\n  src: url("../../node_modules/@fontsource/${f.pkg}/files/${f.pkg}-${subset}-${w}-normal.woff2")\n    format("woff2");\n  unicode-range: ${range};\n}\n`;
    }
  }
}
writeFileSync(new URL("../src/css/fonts.css", import.meta.url), out);
